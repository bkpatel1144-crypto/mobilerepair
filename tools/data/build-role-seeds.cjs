/**
 * Generates `src/config/default-role-grants.ts` from the client's five per-role exports.
 *
 *   node tools/data/build-role-seeds.cjs
 *
 * The five seeded roles used to be modelled from tiers — "full", "createViewUpdate", "viewOnly" —
 * applied to whole modules. That is a reasonable guess, and it was a guess: the client's exports
 * say a Salesman holds 39 permissions across 10 menus and a Technician 13 across 2, and no tier
 * rule reproduces those numbers. They are read straight from the files now, so "same as the
 * reference" is a fact about the data rather than a claim about the modelling.
 *
 * Menus are translated from the reference's slugs to this app's `menuKey()` form. Their module
 * slugs (`service`) are dropped: this app has no separate "module visible" flag — a section shows
 * in the sidebar when any of its leaves does — so only the leaves carry through.
 *
 * A permission for a feature this product does not have is dropped, and the generator prints
 * exactly which. Today that is Manager's four `MASTERS_ATTRIBUTES_*`, an Attributes master this
 * app has no screen for; inventing one to make a number match would be the wrong way round.
 */
const fs = require('node:fs')
const { FEATURE_MAP } = require('./reference-menu-map.cjs')

const OUT = 'src/config/default-role-grants.ts'

const ROLE_FILES = {
  OWNER: 'ownerpermition',
  MANAGER: 'managerpermition',
  SALESMAN: 'salesmanpermition',
  TECHNICIAN: 'tecnicionpermition',
  ACCOUNTANT: 'accountentpermition',
}

/** Reference feature slug -> this app's `menuKey()` (`"service/job-cards"`). */
const MENU_KEY_BY_REF_SLUG = new Map()
for (const [sectionKey, features] of Object.entries(FEATURE_MAP)) {
  for (const [navSlug, refSlug] of Object.entries(features)) {
    MENU_KEY_BY_REF_SLUG.set(refSlug, `${sectionKey}/${navSlug}`)
  }
}

// Quote-agnostic on purpose: the generated catalogue carries JSON double quotes until Prettier
// runs over it, and a single-quote-only pattern silently matched nothing — every role came out
// with zero permissions and the generator reported it as success.
const catalogue = fs.readFileSync('src/config/permission-catalogue.ts', 'utf8')
const knownPermissions = new Set(
  [...catalogue.matchAll(/key: ['"]([A-Z][A-Z0-9_]*)['"]/g)].map((m) => m[1])
)
if (knownPermissions.size < 100) {
  throw new Error(
    `only ${knownPermissions.size} permission keys found in the catalogue — run ` +
      'build-permission-catalogue.cjs first'
  )
}

const roles = {}
const notes = []

for (const [code, file] of Object.entries(ROLE_FILES)) {
  const ref = JSON.parse(fs.readFileSync(`data/${file}.json`, 'utf8'))
  if (ref.role !== code) throw new Error(`${file}.json says ${ref.role}, expected ${code}`)

  const menus = []
  const unmappedMenus = []
  for (const slug of ref.assignedMenus) {
    const key = MENU_KEY_BY_REF_SLUG.get(slug)
    if (key) {
      menus.push(key)
    } else if (!FEATURE_MAP[slug]) {
      // Not a leaf we know and not one of their module slugs either.
      unmappedMenus.push(slug)
    }
  }

  const permissions = ref.permissions.filter((k) => knownPermissions.has(k))
  const dropped = ref.permissions.filter((k) => !knownPermissions.has(k))

  if (unmappedMenus.length) notes.push(`${code}: menus not in this app — ${unmappedMenus.join(', ')}`)
  if (dropped.length) notes.push(`${code}: permissions for features this app lacks — ${dropped.join(', ')}`)

  roles[code] = {
    referenceMenus: ref.assignedMenus.length,
    referencePermissions: ref.permissions.length,
    menus: menus.sort(),
    permissions: permissions.sort(),
  }
}

const header = `// GENERATED by tools/data/build-role-seeds.cjs — do not edit by hand.
//
// Source: data/{owner,manager,salesman,tecnicion,accountent}permition.json
//
${Object.entries(roles)
  .map(
    ([code, r]) =>
      `// ${code.padEnd(11)} ${String(r.menus.length).padStart(2)} menus (export: ${r.referenceMenus} incl. module rows), ` +
      `${String(r.permissions.length).padStart(3)} permissions (export: ${r.referencePermissions})`
  )
  .join('\n')}
${notes.length ? '//\n' + notes.map((n) => `// NOTE ${n}`).join('\n') + '\n' : ''}
/** What one seeded role is granted, straight from the client's export for that role. */
export interface RoleGrant {
  /** \`menuKey()\` values — see \`nav.ts\`. The reference's module rows are not included; this app
   *  shows a section whenever one of its leaves is visible. */
  menus: string[]
  /** \`permission-catalogue.ts\` keys. */
  permissions: string[]
  /** What the export itself claimed, so a test can report the gap rather than hide it. */
  referenceMenus: number
  referencePermissions: number
}

export const DEFAULT_ROLE_GRANTS: Record<string, RoleGrant> = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(roles).map(([code, r]) => [
      code,
      {
        menus: r.menus,
        permissions: r.permissions,
        referenceMenus: r.referenceMenus,
        referencePermissions: r.referencePermissions,
      },
    ])
  ),
  null,
  2
).replace(/"([A-Za-z]\w*)":/g, '$1:')}
`

fs.writeFileSync(OUT, header)
for (const note of notes) console.log('  NOTE', note)
console.log(
  `${OUT}: ` +
    Object.entries(roles)
      .map(([code, r]) => `${code} ${r.menus.length}m/${r.permissions.length}p`)
      .join(', ')
)
